function Ensure-Docker {
    # PS 5.1 wraps redirected native stderr into ErrorRecords: with
    # $ErrorActionPreference=Stop a failing `docker info` would throw before
    # $LASTEXITCODE is checked, so relax it around the daemon probes
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        docker info *> $null
        if ($LASTEXITCODE -eq 0) { return }
        Write-Output "dockercode: Docker daemon not reachable, starting Docker Desktop..."
        $dd = 'C:\Program Files\Docker\Docker\Docker Desktop.exe'
        if (-not (Test-Path $dd)) {
            throw "Docker Desktop not found at $dd - start Docker manually and retry"
        }
        Start-Process $dd | Out-Null
        $deadline = (Get-Date).AddSeconds(180)
        while ((Get-Date) -lt $deadline) {
            Start-Sleep -Seconds 5
            docker info *> $null
            if ($LASTEXITCODE -eq 0) { return }
            Write-Output "  waiting for the Docker engine..."
        }
        throw "Docker engine did not come up within 180s"
    }
    finally {
        $ErrorActionPreference = $prevEap
    }
}

Ensure-Docker

docker system prune -f

# build the image with a fixed container user (see header comment)
$env:USER_UID = '1000'
$env:USER_GID = '1000'

# generate Dockerfile from Dockerfile.template (+ optional Dockerfile.extension)
Write-Output '# Dockerfile GENERATED by bin/build.ps1 - DO NOT EDIT' | Set-Content -Encoding ascii .\Dockerfile
Add-Content -Encoding ascii .\Dockerfile (Get-Content -Raw .\Dockerfile.template)
if (Test-Path .\Dockerfile.extension) {
    $ext = Get-Content -Raw .\Dockerfile.extension
    $gen = Get-Content -Raw .\Dockerfile
    $gen = $gen.Replace('INCLUDED_EXTENSION', $ext)
    [IO.File]::WriteAllText((Resolve-Path .\Dockerfile), $gen, (New-Object System.Text.UTF8Encoding($false)))
}
else {
    $gen = Get-Content -Raw .\Dockerfile
    $gen = $gen.Replace('INCLUDED_EXTENSION', '')
    [IO.File]::WriteAllText((Resolve-Path .\Dockerfile), $gen, (New-Object System.Text.UTF8Encoding($false)))
}

docker compose build
exit $LASTEXITCODE
